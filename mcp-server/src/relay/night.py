class PlanDraft(BaseModel):
    """Una tarea propuesta por el LLM (pre-validación)."""
    title: str = Field(description="Descripción técnica imperativa, una frase")
    refs: list[str] = Field(description="Paths relativos al repo, de la lista dada")

    @field_validator("refs", mode="before")
    @classmethod
    def _unwrap_minimax_item(cls, v: Any) -> Any:
        """La capa de function-calling de MiniMax M3 mangla arrays de
        strings anidados: el modelo emite `"refs": ["a", "b"]` (visible
        en su thinking) pero los args llegan como `{"item": [...]}` o
        `{"item": "solo-uno"}`. Es del provider, no del modelo — los 4
        retries fallaban idéntico. Aceptar ambas formas. Caso real:
        un run de ejemplo commercedemo 2026-07-10."""
        if isinstance(v, dict) and set(v) == {"item"}:
            v = v["item"]
        if isinstance(v, str):
            v = [v]
        return v


class PlanDrafts(BaseModel):
    tasks: list[PlanDraft] = Field(default_factory=list)


